//! The clipboard both ways (kind 32, Sill's `Clipboard` and `ClipboardPolicy`), ported. Pure.
//!
//! A device sends kind 32 only to a host whose window list says `clipboard` 1 (text). Any kind 32
//! subscribes it; `{"stop":true}` ends that; text sets this machine's clipboard and goes to every
//! other subscriber. A subscription or text is taken at most 4 times a second per connection, a
//! stop always. This machine's copies go to every subscriber, but never one a password manager
//! marks, never this host's own write, never more than 256 KB of text.

use serde::Deserialize;

/// `WindowList.clipboard`: text.
pub const GENERATION: i64 = 1;
pub const MAX_TEXT_BYTES: usize = 256 * 1024;
pub const MAX_PAYLOAD: usize = 1 << 20;
pub const PER_SECOND: usize = 4;

/// MIME types that mark a copy as a secret or a moment's: KDE's password-manager hint (KeePassXC,
/// KDE's own), and the nspasteboard.org markers some apps put on Linux too, as Sill for Mac skips.
/// Never sent, and the text is never even read.
pub const MARKERS: [&str; 6] = [
    "x-kde-passwordManagerHint",
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "de.petermaurer.TransientPasteboardType",
    "com.agilebits.onepassword",
];

pub fn marked(types: &[String]) -> bool {
    types.iter().any(|t| MARKERS.contains(&t.as_str()))
}

/// The kind 32 payload that sets the other side's clipboard to `text`: None when empty or too long.
pub fn payload(text: &str) -> Option<Vec<u8>> {
    if text.is_empty() || text.len() > MAX_TEXT_BYTES {
        return None;
    }
    let data = serde_json::to_vec(&serde_json::json!({ "text": text })).ok()?;
    (data.len() <= MAX_PAYLOAD).then_some(data)
}

#[derive(Debug, PartialEq)]
pub enum FromDevice {
    Subscribe,
    Set(String),
    Stop,
    Refuse(&'static str),
}

/// What a device's kind 32 asks: `stop` wins; text that is not empty sets; anything else subscribes.
pub fn from_device(payload: &[u8]) -> FromDevice {
    #[derive(Deserialize)]
    struct Clip {
        text: Option<String>,
        stop: Option<bool>,
    }
    let Ok(c) = serde_json::from_slice::<Clip>(payload) else { return FromDevice::Refuse("undecodable") };
    if c.stop == Some(true) {
        return FromDevice::Stop;
    }
    match c.text {
        Some(t) if !t.is_empty() && t.len() > MAX_TEXT_BYTES => FromDevice::Refuse("too long"),
        Some(t) if !t.is_empty() => FromDevice::Set(t),
        _ => FromDevice::Subscribe,
    }
}

/// A device's kind 32 at `now` with its connection's `arrivals` (the times of its subscriptions and
/// texts taken in the last second): what it asks, refused past the rate; a stop is never limited.
pub fn host_receives(payload: &[u8], arrivals: &mut Vec<f64>, now: f64) -> FromDevice {
    let ask = from_device(payload);
    if !matches!(ask, FromDevice::Subscribe | FromDevice::Set(_)) {
        return ask;
    }
    arrivals.retain(|t| now - t < 1.0);
    if arrivals.len() >= PER_SECOND {
        return FromDevice::Refuse("rate");
    }
    arrivals.push(now);
    ask
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_wire() {
        assert_eq!(from_device(b"{}"), FromDevice::Subscribe);
        assert_eq!(from_device(br#"{"text":""}"#), FromDevice::Subscribe);
        assert_eq!(from_device(br#"{"text":"hi","stop":true}"#), FromDevice::Stop);
        assert_eq!(from_device(br#"{"text":"hi"}"#), FromDevice::Set("hi".into()));
        assert_eq!(from_device(b"nope"), FromDevice::Refuse("undecodable"));
        let long = format!(r#"{{"text":"{}"}}"#, "x".repeat(MAX_TEXT_BYTES + 1));
        assert_eq!(from_device(long.as_bytes()), FromDevice::Refuse("too long"));
        assert_eq!(payload("a\"b").unwrap(), br#"{"text":"a\"b"}"#);
        assert!(payload("").is_none() && payload(&"x".repeat(MAX_TEXT_BYTES + 1)).is_none());
        assert!(payload(&"x".repeat(MAX_TEXT_BYTES)).is_some());
    }

    #[test]
    fn rate_and_markers() {
        let mut a = Vec::new();
        for i in 0..4 {
            assert_eq!(host_receives(b"{}", &mut a, i as f64 * 0.1), FromDevice::Subscribe);
        }
        assert_eq!(host_receives(b"{}", &mut a, 0.5), FromDevice::Refuse("rate"));
        assert_eq!(host_receives(br#"{"stop":true}"#, &mut a, 0.5), FromDevice::Stop, "a stop is never limited");
        assert_eq!(host_receives(b"{}", &mut a, 1.05), FromDevice::Subscribe);
        assert!(marked(&["text/plain".into(), "x-kde-passwordManagerHint".into()]));
        assert!(!marked(&["text/plain;charset=utf-8".into()]));
    }
}
